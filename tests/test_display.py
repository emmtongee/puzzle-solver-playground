from src.utils.display import format_n_queens_board, format_sudoku_board

def test_n_queens_display_format():
    assert format_n_queens_board([1, 3, 0, 2]) == (
        ". Q . .\n"
        ". . . Q\n"
        "Q . . .\n"
        ". . Q ."
    )

def test_sudoku_display_format():
    board = [
        [5, 3, 0, 0, 7, 0, 0, 0, 0], 
        [6, 0, 0, 1, 9, 5, 0, 0, 0], 
        [0, 9, 8, 0, 0, 0, 0, 6, 0], 
        [8, 0, 0, 0, 6, 0, 0, 0, 3], 
        [4, 0, 0, 8, 0, 3, 0, 0, 1], 
        [7, 0, 0, 0, 2, 0, 0, 0, 6], 
        [0, 6, 0, 0, 0, 0, 2, 8, 0], 
        [0, 0, 0, 4, 1, 9, 0, 0, 5], 
        [0, 0, 0, 0, 8, 0, 0, 7, 9]
    ]
    assert format_sudoku_board() == (
        "5 3 . | . 7 . | . . .\n"
        "6 . . | 1 9 5 | . . .\n"
        ". 9 8 | . . . | . 6 .\n"
        "------+-------+------\n"
        "8 . . | . 6 . | . . 3\n"
        "4 . . | 8 . 3 | . . 1\n"
        "7 . . | . 2 . | . . 6\n"
        "------+-------+------\n"
        ". 6 . | . . . | 2 8 .\n"
        ". . . | 4 1 9 | . . 5\n"
        ". . . | . 8 . | . 7 9"
    )