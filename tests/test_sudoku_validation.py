from src.solvers.sudoku import sudoku_is_safe, sudoku_board_is_valid


def test_row_conflict():
    board = [
        [5, 3, 0, 0, 7, 0, 0, 0, 0], # 8th cell -> 5, conflict with 5 on the left
        [6, 0, 0, 1, 9, 5, 0, 0, 0], 
        [0, 9, 8, 0, 0, 0, 0, 6, 0], 
        [8, 0, 0, 0, 6, 0, 0, 0, 3], 
        [4, 0, 0, 8, 0, 3, 0, 0, 1], 
        [7, 0, 0, 0, 2, 0, 0, 0, 6], 
        [0, 6, 0, 0, 0, 0, 2, 8, 0], 
        [0, 0, 0, 4, 1, 9, 0, 0, 5],
        [0, 0, 0, 0, 8, 0, 0, 7, 9]  
    ]
    assert not sudoku_is_safe(board, 0, 7, 5)

def test_column_conflict():
    board = [
        [5, 3, 0, 0, 7, 0, 0, 0, 0], 
        [6, 0, 0, 1, 9, 5, 0, 0, 0], 
        [0, 9, 8, 0, 0, 0, 0, 6, 0], 
        [8, 0, 0, 0, 6, 0, 0, 0, 3], 
        [4, 0, 0, 8, 0, 3, 0, 0, 1], 
        [7, 0, 0, 0, 2, 0, 0, 0, 6], 
        [0, 6, 0, 0, 0, 0, 2, 8, 0], 
        [0, 0, 0, 4, 1, 9, 0, 0, 5], # 3rd cell -> 8, conflict with 8 above
        [0, 0, 0, 0, 8, 0, 0, 7, 9]
    ]
    assert not sudoku_is_safe(board, 7, 2, 8)

